-- Oelek public ratings. Run in the Supabase SQL Editor as project owner.
-- Enable Authentication > Sign In / Providers > Anonymous sign-ins separately.
-- Namespaced objects can coexist with Tea Time in the same project.
begin;
create table if not exists public.oelek_sambals (id text primary key);
alter table public.oelek_sambals enable row level security;
revoke all on public.oelek_sambals from anon, authenticated;

create table if not exists public.oelek_ratings (
  sambal_id text not null references public.oelek_sambals(id),
  user_id uuid not null references auth.users(id) on delete cascade,
  stars smallint not null check (stars between 1 and 5),
  updated_at timestamptz not null default now(),
  primary key (sambal_id,user_id)
);
alter table public.oelek_ratings enable row level security;
revoke all on public.oelek_ratings from anon, authenticated;
grant select on public.oelek_ratings to authenticated;
drop policy if exists "oelek read own vote" on public.oelek_ratings;
create policy "oelek read own vote" on public.oelek_ratings for select to authenticated using (user_id = (select auth.uid()));

-- An atomic counter counts every change/removal, including repeated edits of one vote.
create table if not exists public.oelek_rating_limits (
  user_id uuid primary key references auth.users(id) on delete cascade,
  window_start timestamptz not null,
  changes integer not null
);
alter table public.oelek_rating_limits enable row level security;
revoke all on public.oelek_rating_limits from anon, authenticated;

create or replace function public.oelek_rate(p_sambal text,p_stars integer)
returns void language plpgsql security definer set search_path = '' as $$
declare voter uuid := auth.uid(); accepted uuid;
begin
  if voter is null then raise exception 'An anonymous session is required'; end if;
  if p_stars is null or p_stars < 0 or p_stars > 5 then raise exception 'Stars must be between 0 and 5'; end if;
  if not exists(select 1 from public.oelek_sambals where id=p_sambal) then raise exception 'Unknown sambal'; end if;
  insert into public.oelek_rating_limits as limits(user_id,window_start,changes)
    values(voter,now(),1)
    on conflict(user_id) do update set
      window_start=case when limits.window_start <= now()-interval '1 hour' then now() else limits.window_start end,
      changes=case when limits.window_start <= now()-interval '1 hour' then 1 else limits.changes+1 end
    where limits.window_start <= now()-interval '1 hour' or limits.changes < 60
    returning user_id into accepted;
  if accepted is null then raise exception 'Too many ratings this hour'; end if;
  if p_stars=0 then
    delete from public.oelek_ratings where sambal_id=p_sambal and user_id=voter;
  else
    insert into public.oelek_ratings(sambal_id,user_id,stars) values(p_sambal,voter,p_stars)
      on conflict(sambal_id,user_id) do update set stars=excluded.stars,updated_at=now();
  end if;
end $$;
revoke all on function public.oelek_rate(text,integer) from public, anon;
grant execute on function public.oelek_rate(text,integer) to authenticated;

-- Owner-rights aggregate exposes totals only, never voter identities.
create or replace view public.oelek_rating_totals with (security_invoker=false) as
select sambal_id,count(*)::int n,round(avg(stars)::numeric,2) avg_stars,
 count(*) filter(where stars=1)::int s1,count(*) filter(where stars=2)::int s2,
 count(*) filter(where stars=3)::int s3,count(*) filter(where stars=4)::int s4,
 count(*) filter(where stars=5)::int s5
from public.oelek_ratings group by sambal_id;
revoke all on public.oelek_rating_totals from anon,authenticated;
grant select on public.oelek_rating_totals to anon,authenticated;

